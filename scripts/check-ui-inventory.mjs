// Validate the bounded reference-to-implementation audit without inspecting a desktop.
// --write refreshes the generated report; the default checks that it is current.
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { resolve, relative, isAbsolute, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const json = path => JSON.parse(readFileSync(resolve(root, path), 'utf8').replace(/^\uFEFF/, ''));
const audit = json('docs/ui-controls.json');
const inventory = json('docs/ui-inventory.json');
const roadmap = json('sites/capture-workbench/roadmap.json');
const releases = new Set(json('sites/capture-workbench/release-data.json').releases.map(r => r.version));
const surfaces = new Map(inventory.surfaces.map(s => [s.surface, s]));
const features = new Map(roadmap.features.map(f => [f.id, f]));
const labels = { missing: 'Missing', partial: 'Partial', local_verified: 'Local verified; release or native checks remain', native_verified: 'Native verified within stated scope' };
const exists = path => {
  assert.equal(typeof path, 'string');
  const abs = resolve(root, path), rel = relative(root, abs);
  assert(rel && !rel.startsWith('..') && !isAbsolute(rel), `Evidence outside workspace: ${path}`);
  assert(existsSync(abs), `Missing evidence: ${path}`);
};
assert.equal(audit.schema_version, 1);
assert.equal(new Set(audit.surfaces).size, audit.surfaces.length);
audit.code_sources.forEach(exists);
const ids = new Set(), mappedEntries = new Set();
const states = Object.fromEntries(Object.keys(labels).map(key => [key, 0]));
const rows = [];
let readyCount = 0;
for (const group of audit.groups) {
  const surface = surfaces.get(group.surface);
  assert(surface && audit.surfaces.includes(group.surface), `Unknown surface: ${group.surface}`);
  assert(surface.controls.includes(group.observed_entry), `Unknown observed entry: ${group.observed_entry}`);
  const entryKey = `${group.surface}\n${group.observed_entry}`;
  assert(!mappedEntries.has(entryKey), `Duplicate observed entry: ${entryKey}`);
  mappedEntries.add(entryKey);
  assert.equal(group.reference_evidence, surface.evidence);
  exists(group.reference_evidence);
  assert(['presence_only', 'cancel_preserved_document'].includes(group.reference_check));
  assert(group.controls.length);
  for (const control of group.controls) {
    assert(/^[a-z][a-z0-9.-]+$/.test(control.id) && !ids.has(control.id), `Invalid/duplicate control: ${control.id}`);
    ids.add(control.id);
    const feature = features.get(control.feature_id);
    assert(feature, `Unknown feature: ${control.feature_id}`);
    assert(labels[control.implementation_state], `Unknown state: ${control.id}`);
    assert(control.label?.trim() && control.notes?.trim());
    control.evidence.forEach(exists);
    control.native_evidence.forEach(exists);
    if (['local_verified', 'native_verified'].includes(control.implementation_state)) assert(control.evidence.length, `No behavior evidence: ${control.id}`);
    if (control.implementation_state === 'native_verified') assert(control.native_evidence.length && releases.has(control.released_in), `No native evidence or published release: ${control.id}`);
    if (control.released_in) assert(releases.has(control.released_in), `Unknown release: ${control.id}`);
    const ready = control.implementation_state === 'native_verified' && feature.status === 'shipped' && feature.evidence.length > 0 && releases.has(feature.released_in);
    const target = features.get(control.followup_feature_id ?? control.feature_id);
    if (!ready) assert(target?.status !== 'shipped' && ((target?.target_version && target.target_provisional) || target?.schedule_status === 'unscheduled'), `Unfinished scope needs a target or explicit unscheduled feature: ${control.id}`);
    const badge = ready ? 'Ready (scoped behavior)' : target.missed_target_version ? `Overdue ${target.missed_target_version}` : target.target_version ? `Target ${target.target_version} (provisional)` : 'Unscheduled';
    if (ready) readyCount++;
    states[control.implementation_state]++;
    rows.push({ group, control, badge });
  }
}
for (const name of audit.surfaces) {
  const surface = surfaces.get(name);
  assert(surface, `Unknown declared surface: ${name}`);
  for (const entry of surface.controls) assert(mappedEntries.has(`${name}\n${entry}`), `Unmapped entry in declared surface: ${name}: ${entry}`);
}
const escape = value => String(value).replaceAll('|', '\\|').replaceAll('\n', ' ');
const lines = ['# ClipCraft control implementation audit', '', `Updated: ${audit.updated}. Generated by \`node scripts/check-ui-inventory.mjs --write\`.`, '', audit.scope, '',
  `${ids.size} individual controls map ${mappedEntries.size} recorded observation entries across ${audit.surfaces.length} of ${surfaces.size} recorded surfaces. ${surfaces.size - audit.surfaces.length} surfaces still need a detailed mapping; other application surfaces remain unobserved.`, '',
  'Targets and feature statuses are read from the canonical roadmap. This audit does not turn desktop labels green automatically. “Ready” here means the narrow behavior has native evidence and a known published release; it does not claim matching layout, every option, or behavior observed in the reference application. A feature still needing reference verification remains red even when part of it has shipped.', '',
  'Reference checks are presence-only unless the ledger explicitly records Cancel preservation. Applied behavior is not inferred from control presence. Combined labels are split so one working part cannot hide an unfinished neighbor.', ''];
for (const surface of audit.surfaces) {
  lines.push(`## ${surface}`, '', `Reference: ${surfaces.get(surface).evidence}.`, '', '| Control | Feature | Implementation | Badge eligibility | Evidence and remaining work |', '| --- | --- | --- | --- | --- |');
  for (const {control:c, badge} of rows.filter(r => r.group.surface === surface)) {
    const evidence = c.evidence.length ? ` Evidence: ${c.evidence.join(', ')}.` : '';
    lines.push(`| ${escape(c.label)} (${c.id}) | ${c.feature_id}${c.followup_feature_id ? ` / ${c.followup_feature_id}` : ''} | ${labels[c.implementation_state]} | ${badge} | ${escape(c.notes + evidence)} |`);
  }
  lines.push('');
}
lines.push('## Remaining mapping surfaces', '', ...inventory.surfaces.filter(s => !audit.surfaces.includes(s.surface)).map(s => `- ${s.surface}`), '', 'Next: map the remaining saved tool/menu surfaces and inspect their behavior using synthetic content. Common-dialog inspection is separately blocked; do not infer hidden picker behavior from a label.', '');
const markdown = lines.join('\n');
const reportPath = resolve(root, 'docs/ui-controls.md');
if (process.argv.includes('--write')) writeFileSync(reportPath, markdown);
else assert.equal(readFileSync(reportPath, 'utf8'), markdown, 'Generated report is stale; use --write.');
const report = { passed: true, mapped_surfaces: audit.surfaces.length, recorded_surfaces: surfaces.size, mapped_observation_entries: mappedEntries.size, controls: ids.size, states, ready_scopes: readyCount, full_ui_parity: false };
mkdirSync(resolve(root, 'artifacts/ui-inventory'), { recursive: true });
writeFileSync(resolve(root, 'artifacts/ui-inventory/checks.json'), JSON.stringify(report, null, 2) + '\n');
console.log(JSON.stringify(report));
