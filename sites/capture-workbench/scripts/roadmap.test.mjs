import test from 'node:test';
import assert from 'node:assert/strict';
import { validateRoadmap, renderRoadmap, renderRoadmapMarkdown, renderTarget } from './roadmap.mjs';
const sample = () => ({schema_version:1,updated:'2026-10-29',scope:'Test backlog',features:[{id:'CAP-001',title:'Capture',category:'Capture',status:'planned',priority:'next',description:'Missing feature',completion:'Verify export',evidence:[],updated:'2026-10-29',target_version:'0.1.0-alpha.5',target_provisional:true}]});
test('shipped status cannot hide missing evidence or an unknown release', () => {
  const roadmap = sample(); roadmap.features[0].status = 'shipped';
  delete roadmap.features[0].target_version;
  assert.throws(() => validateRoadmap(roadmap, ['0.1.0']), /evidence/);
  roadmap.features[0].evidence = ['Verified export']; roadmap.features[0].released_in = '9.0.0';
  assert.throws(() => validateRoadmap(roadmap, ['0.1.0']), /known release/);
  roadmap.features[0].released_in = '0.1.0';
  assert.equal(validateRoadmap(roadmap, ['0.1.0']).features[0].status, 'shipped');
});
test('unfinished features require explicit provisional targets without implying delivery', () => {
  const roadmap = sample();
  assert.equal(validateRoadmap(roadmap, []).features[0].status, 'planned');
  assert.match(renderRoadmap(roadmap).ROADMAPROWS, /Target v0\.1\.0-alpha\.5.*provisional/);
  assert.match(renderRoadmapMarkdown(roadmap), /Provisional target: 0\.1\.0-alpha\.5/);
  assert.doesNotMatch(renderRoadmap(roadmap).ROADMAPROWS, /Released in|Ready/);
  roadmap.features[0].target_provisional = false;
  assert.throws(() => validateRoadmap(roadmap, []), /provisional target/);
  roadmap.features[0].target_provisional = true;
  delete roadmap.features[0].target_version;
  assert.throws(() => validateRoadmap(roadmap, []), /unscheduled/);
  roadmap.features[0].target_version = '<img src=x onerror=alert(1)>';
  assert.throws(() => validateRoadmap(roadmap, []), /provisional target/);
  assert.match(renderTarget(roadmap.features[0]), /&lt;img/);
  roadmap.features[0].status = 'shipped';
  assert.equal(renderTarget(roadmap.features[0]), '');
});
test('missed targets remain visible beside active work or an unscheduled release', () => {
  const roadmap = sample(), feature = roadmap.features[0];
  feature.original_target_version = feature.missed_target_version = '0.1.0-alpha.3';
  feature.target_history = ['0.1.0-alpha.3','0.1.0-alpha.5'];
  assert.equal(validateRoadmap(roadmap, []).features[0].status, 'planned');
  assert.match(renderTarget(feature), /Overdue.*alpha\.3/);
  assert.match(renderTarget(feature), /Target v0\.1\.0-alpha\.5/);
  delete feature.target_version;
  feature.schedule_status = 'unscheduled';
  validateRoadmap(roadmap, []);
  assert.match(renderTarget(feature), /Overdue.*alpha\.3/);
  assert.match(renderTarget(feature), /Release not scheduled/);
  assert.match(renderRoadmapMarkdown(roadmap), /OVERDUE/);
  feature.missed_target_version = '0.1.0-alpha.4';
  assert.throws(() => validateRoadmap(roadmap, []), /original unfinished/);
});
test('unknown statuses, duplicate IDs, and missing dependency targets fail', () => {
  const roadmap = sample(); roadmap.features[0].status = 'maybe';
  assert.throws(() => validateRoadmap(roadmap, []), /status/);
  roadmap.features[0].status = 'planned'; roadmap.features.push({...roadmap.features[0]});
  assert.throws(() => validateRoadmap(roadmap, []), /duplicate/);
  roadmap.features.pop(); roadmap.features[0].depends_on = ['CAP-999'];
  assert.throws(() => validateRoadmap(roadmap, []), /dependency/);
});
test('rendered counts reflect the inventory and descriptions remain inert text', () => {
  const roadmap = sample(); roadmap.features[0].description = '<script>alert(1)</script>';
  const rendered = renderRoadmap(roadmap);
  assert.match(rendered.ROADMAPSTATS, /<b>1<\/b><span>Planned/);
  assert.match(rendered.ROADMAPROWS, /&lt;script&gt;/);
  assert.ok(!rendered.ROADMAPROWS.includes('<script>'));
});
